def check_turns(a):
    """Byte-exact check: training context == eval prompt; loss mask == exactly the generated tokens."""
    import random
    import numpy as np
    from src.train import data as D
    from .common import apex_path
    model = str(apex_path("model_dir"))
    D._init_worker(model, True)          # global default of every config; per-record override must win
    tok = D._TOK
    lines = []
    for split, n in (("train", a.n_check), ("val", max(5, a.n_check // 4))):
        ls = [ln for ln in open(processed_dir(EXPERT_TURNS) / f"{split}.jsonl") if ln.strip()]
        lines += random.Random(0).sample(ls, min(n, len(ls)))
    bad, n_lab = [], 0
    for ln in lines:
        rec = json.loads(ln)
        msgs = D.normalize_messages(rec["messages"])
        prompt = tok.apply_chat_template(msgs[:-1], tools=None, tokenize=False, add_generation_prompt=True,
                                         enable_thinking=True, preserve_thinking=False)
        text = D.render_text(rec, tok, preserve_thinking=False)
        fin = msgs[-1]
        want_tail = fin.get("reasoning_content", "") + "\n</think>\n\n" + fin["content"] + "<|im_end|>\n"
        r = D.tokenize_record(ln)
        ids, mask = r["ids"], r["mask"]
        p_ids = tok.encode(prompt, add_special_tokens=False)
        last_end = int(np.nonzero(ids == D._TOK_CFG["im_end"])[0][-1])
        expect = np.zeros_like(mask); expect[len(p_ids): last_end + 1] = 1
        errs = []
        if not text.startswith(prompt):
            errs.append("text_prefix")
        elif text[len(prompt):] != want_tail:
            errs.append("tail")
        if prompt.count("<think>") != 1 or not prompt.endswith("<|im_start|>assistant\n<think>\n"):
            errs.append("prompt_thinking")
        if list(ids[: len(p_ids)]) != p_ids:
            errs.append("token_prefix")
        if not np.array_equal(mask, expect):
            errs.append(f"mask(got {int(mask.sum())} want {int(expect.sum())})")
        n_lab += int(mask.sum())
        if errs:
            bad.append((rec["id"], errs))
    print(json.dumps({"checked": len(lines), "failures": len(bad), "examples": bad[:5],
                      "label_tokens_in_checked": n_lab}))
    if bad:
        raise SystemExit(1)


