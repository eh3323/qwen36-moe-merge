TRAJ_REPO, TRAJ_REV = "ai-and/termgrade-trajectories", "7d584d63dd598d7e76d444ca23e1527fb5ebd6d9"
ENV_REPO, ENV_REV = "ai-and/termgrade-environments", "3a34ba29ddcd4cbbcbf8840c64f67e853f9b8b0d"
RAW_KEY = "termgrade"
EXPERT = "tb_v2"
MODELS = {"deepseek": 0, "glm": 0, "qwen": 1, "gemma_think": 2}   # teacher -> preference rank (0 = best)
MAX_TOKENS = 65536
HARD_MAX = 0.5                     # tier 1: 0 < pooled pass rate <= 0.5
TIER2_MAX = 0.67                   # tier 2, only if tier 1 cannot fill the budget
MAX_PER_TASK = 2
N_VAL_TASKS = 20
TOKEN_BUDGET = 15_022_992          # E-TB train tokens (tb_stats.json), for a token-matched comparison
MIN_TURNS = 3                      # assistant turns; 1-2 turn "write the file and finish" traces teach little

_CATS = [("c_cpp", r"\b(gcc|g\+\+|clang|makefile|cmake|\.c\b|\.cpp\b|c\+\+|segfault)"),
         ("rust_go_java", r"\b(cargo|rustc|golang|go build|\.go\b|javac|maven|gradle|\.java\b)"),
         ("db_sql", r"\b(sqlite|postgres|mysql|sql\b|database)"),
         ("network", r"\b(http|nginx|socket|tcp|udp|port \d+|curl|server|grpc|dns)\b"),
         ("system_admin", r"\b(systemd|cron|iptables|useradd|chmod|permissions|mount|ssh|logrotate|tar)\b"),
         ("git", r"\bgit\b"),
         ("python", r"\b(python|\.py\b|pip)\b"),
         ("shell_text", r"\b(bash|awk|sed|grep|jq|csv|json|log)\b")]


def category(instruction: str) -> str:
    low = instruction.lower()
    for name, pat in _CATS:
        if re.search(pat, low):
            return name
    return "other"


# ----------------------------------------------------------------------------- download
def download(a):
    from huggingface_hub import snapshot_download
    dest = raw_dir(RAW_KEY)
    t0 = time.time()
    traj_files = ["README.md", "data/trials.parquet"] + [f"data/messages/{m}.parquet" for m in MODELS]
    snapshot_download(repo_id=TRAJ_REPO, repo_type="dataset", revision=TRAJ_REV, allow_patterns=traj_files,
                      local_dir=str(dest / "trajectories"))
    snapshot_download(repo_id=ENV_REPO, repo_type="dataset", revision=ENV_REV,
                      allow_patterns=["README.md", "tasks.jsonl", "task_source.jsonl", "labels.jsonl",
                                      "run_config.yaml"], local_dir=str(dest / "environments"))
    (dest / "REVISIONS.json").write_text(json.dumps({TRAJ_REPO: TRAJ_REV, ENV_REPO: ENV_REV}, indent=1))
    log(f"[{EXPERT}] downloaded to {dest} in {time.time() - t0:.0f}s")


# ----------------------------------------------------------------------------- task table
def task_table(drops: DropCounter) -> dict:
    """task -> {pooled, per_model, split, instruction, tier, category}; decontaminated, hard tiers only."""
    import pandas as pd
    from .convert_terminus import Unconvertible, parse_first_user
    from .decontam import tb2_ngram_index, tb_name_verdict
    root = raw_dir(RAW_KEY)
    tr = pd.read_parquet(guard_path(root / "trajectories" / "data" / "trials.parquet"),
                         columns=["task", "model", "reward", "counts_toward_k", "contaminated"])
    tr = tr[tr.counts_toward_k == True]  # noqa: E712
    pooled = tr.groupby("task").reward.apply(lambda r: float((r == 1).mean())).to_dict()
    per_model = tr.groupby(["task", "model"]).reward.apply(lambda r: float((r == 1).mean())).unstack().to_dict("index")
    contaminated = set(tr[tr.contaminated == True].task)  # noqa: E712
    meta = {r["task"]: r for r in read_jsonl(root / "environments" / "tasks.jsonl")}
    src = {r["task"]: r for r in read_jsonl(root / "environments" / "task_source.jsonl")}

    # reference texts that must not overlap: TB2 (instruction+solution+tests, via decontam), TBLite dev, E-TB val
    tb2 = tb2_ngram_index()
    dev = NgramIndex(n=13, max_refs=0)
    tbl = raw_dir("tblite")
    for d in sorted(p for p in tbl.iterdir() if (p / "instruction.md").exists()):
        dev.add(f"TBLite:{d.name}", (d / "instruction.md").read_text())
    for r in read_jsonl(APEX / "data" / "processed" / "tb" / "val.jsonl"):
        try:
            dev.add(f"ETBval:{r['id']}", parse_first_user(r["messages"][0]["content"])[0])
        except Unconvertible:
            pass
    dev.finalize()

    out = {}
    for t, p in pooled.items():
        m = meta.get(t, {})
        if not (m.get("gradable") and m.get("oracle_verified")):
            drops.drop("task:not_gradable_or_oracle_unverified"); continue
        if t in contaminated:
            drops.drop("task:flagged_contaminated"); continue
        if p <= 0:
            drops.drop("task:unsolved_by_all"); continue
        if p > TIER2_MAX:
            drops.drop("task:too_easy"); continue
        s = src.get(t)
        if not s:
            drops.drop("task:no_source"); continue
        instr = s["instruction"]
        if tb_name_verdict(t, instr):
            drops.drop("task:decontam_tb2_name"); continue
        k, _ = tb2.hits(instr + "\n" + (s.get("solution_sh") or ""))
        if k >= 3:
            drops.drop("task:decontam_tb2_13gram"); continue
        k, _ = dev.hits(instr)
        if k >= 3:
            drops.drop("task:decontam_dev_13gram"); continue
        out[t] = {"task": t, "pooled": round(p, 4), "per_model": {k2: (None if v != v else round(v, 3))
                                                                   for k2, v in per_model.get(t, {}).items()},
                  "split": m.get("split"), "tier": 1 if p <= HARD_MAX else 2, "category": category(instr),
                  "instruction_sha": sha256_text(instr)}
    log(f"[{EXPERT}] tasks kept {len(out)} (tier1 {sum(v['tier'] == 1 for v in out.values())}); drops {dict(drops)}")
    return out


# ----------------------------------------------------------------------------- conversion
def convert(row: dict) -> tuple[list[dict], dict]:
    from .convert_terminus import (_FENCE, _SUMMARY_MARKERS, Unconvertible, clean_observation, parse_first_user,
                                   parse_t2_json, render_first_user)
    ms = row["messages"]
    if isinstance(ms, str):
        ms = json.loads(ms)
    ms = list(ms)
    if len(ms) < 4 or ms[0]["role"] != "system" or ms[1]["role"] != "user":
        raise Unconvertible("bad_prefix_roles")
    instr, term = parse_first_user((ms[0]["content"] or "") + (ms[1]["content"] or ""))
    msgs = [{"role": "user", "content": render_first_user(instr, term)}]
    rest = ms[2:]
    while rest and rest[-1]["role"] != "assistant":
        rest = rest[:-1]
    parsed, n_reason = [], 0
    for i, m in enumerate(rest):
        want = "assistant" if i % 2 == 0 else "user"
        if m["role"] != want:
            raise Unconvertible("role_alternation")
        c = m.get("content") or ""
        if want == "user":
            if any(s in c for s in _SUMMARY_MARKERS):
                raise Unconvertible("summarization_or_system_warning")
            if c.startswith("Previous response had parsing errors"):
                raise Unconvertible("parse_errors")
            msgs.append({"role": "user", "content": clean_observation(c)})
        else:
            body = c.strip()
            fm = _FENCE.match(body)
            if fm:
                body = fm.group(1).strip()
            parsed.append(parse_t2_json(body))
            r = (m.get("reasoning_content") or "").strip()
            n_reason += bool(r)
            msgs.append({"role": "assistant", "content": body, "reasoning_content": r})
    if not parsed:
        raise Unconvertible("no_assistant_turn")
    if parsed[-1].get("task_complete") is not True:
        raise Unconvertible("final_turn_not_complete")
    if n_reason == 0:
        raise Unconvertible("no_reasoning_any_turn")
    return msgs, {"instruction": instr, "n_turns": len(parsed), "turns_with_reasoning": n_reason}


def _worker(args):
    from .build import _finish_sample
    from .convert_terminus import Unconvertible
    model, row, t = args
    try:
        msgs, st = convert(row)
    except Unconvertible as e:
        return None, f"convert:{e}"
    except Exception as e:  # noqa
        return None, f"convert_crash:{type(e).__name__}"
    if st["n_turns"] < MIN_TURNS:
        return None, "too_few_turns"
    s = {"id": f"{EXPERT}/{model}/{row['trial']}", "source": f"termgrade_{model}",
         "instance_id": f"termgrade:{row['task']}", "messages": msgs, "tools": None,
         "meta": {"expert": "tb", "variant": EXPERT, "task": row["task"], "teacher": model,
                  "teacher_model_id": row.get("model_id"), "trial": row["trial"], "reward": row["reward"],
                  "turns": st["n_turns"], "turns_with_reasoning": st["turns_with_reasoning"],
                  "episodes": row.get("n_episodes"), "pooled_pass": t["pooled"], "tier": t["tier"],
                  "category": t["category"], "termgrade_split": t["split"], "complete": True,
                  "stratum": "verified"}}
    return _finish_sample(s, MAX_TOKENS)


def candidates(tasks: dict, drops: DropCounter, workers: int) -> list[dict]:
    from .build import iter_parquet, run_pool
    root = raw_dir(RAW_KEY) / "trajectories" / "data" / "messages"
    cols = ["task", "model", "trial", "messages", "reward", "n_episodes", "model_id", "status",
            "counts_toward_k", "exceeded_cap", "contaminated"]

    def rows():
        for model in MODELS:
            for r in iter_parquet(root / f"{model}.parquet", columns=cols, batch_size=32):
                if r["task"] not in tasks:
                    continue
                if r["reward"] != 1 or not r["counts_toward_k"] or r["status"] != "scored":
                    drops.drop(f"{model}:not_verified_pass"); continue
                if r["exceeded_cap"] or r["contaminated"]:
                    drops.drop(f"{model}:capped_or_flagged"); continue
                yield model, r, tasks[r["task"]]
    out = []
    for s, why in run_pool(_worker, rows(), workers):
        if s is None:
            drops.drop(f"traj:{why}")
        else:
            out.append(s)
    return out


# ----------------------------------------------------------------------------- selection
def pick_per_task(cs: list[dict], k: int) -> list[dict]:
    """Prefer the strongest teachers, then longer (more turns) trajectories; distinct teachers first."""
    cs = sorted(cs, key=lambda s: (MODELS[s["meta"]["teacher"]], -s["meta"]["turns"], s["id"]))
    out, seen = [], set()
    for s in cs:
        if s["meta"]["teacher"] not in seen:
            out.append(s); seen.add(s["meta"]["teacher"])
        if len(out) == k:
            return out
    for s in cs:
        if s not in out:
            out.append(s)
        if len(out) == k:
            break
    return out


def build(a):
    drops = DropCounter()
    get_tokenizer()
    tasks = task_table(drops)
    write_jsonl(interim_dir(EXPERT) / "tasks.jsonl", tasks.values())
    cands = candidates(tasks, drops, a.workers)
    write_jsonl(interim_dir(EXPERT) / "candidates.jsonl",
                ({k: c[k] for k in ("id", "source", "instance_id", "n_tokens", "meta")} for c in cands))
    by_task = defaultdict(list)
    for c in cands:
        by_task[c["meta"]["task"]].append(c)
    usable = [t for t in tasks if by_task.get(t)]
    # held-out val tasks: tier-1 tasks chosen by a stable hash, never used for training
    val_tasks = sorted((t for t in usable if tasks[t]["tier"] == 1),
                       key=lambda t: stable_hash01(t, EXPERT + "|val"))[:N_VAL_TASKS]
    val = [pick_per_task(by_task[t], 1)[0] for t in val_tasks]
    # train: tier 1 hardest-first, then tier 2 only while under budget
    order = sorted((t for t in usable if t not in set(val_tasks)),
                   key=lambda t: (tasks[t]["tier"], tasks[t]["pooled"], stable_hash01(t, EXPERT)))
    train, tok = [], 0
    for t in order:
        if tok >= TOKEN_BUDGET:
            drops.drop("select:budget_reached_tasks")
            continue
        for s in pick_per_task(by_task[t], MAX_PER_TASK):
            if tok >= TOKEN_BUDGET:
                break
            train.append(s); tok += s["n_tokens"]
    write_outputs(train, val, tasks, cands, drops)


def write_outputs(train, val, tasks, cands, drops):
    out = processed_dir(EXPERT)
    keep = ("id", "source", "instance_id", "messages", "tools", "n_tokens", "meta")
    write_jsonl(out / "train.jsonl", ({k: c.get(k) for k in keep} for c in train))
    write_jsonl(out / "val.jsonl", ({k: c.get(k) for k in keep} for c in val))
    mani = APEX / "data" / "manifests"
    for name, rows in (("train", train), ("val", val)):
        with open(mani / f"{EXPERT}_{name}.csv", "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["id", "source", "instance_id", "n_tokens", "sha256"])
            for c in sorted(rows, key=lambda c: c["id"]):
                w.writerow([c["id"], c["source"], c["instance_id"], c["n_tokens"], sample_sha(c)])

    def dist(rows, key):
        return dict(Counter(key(c) for c in rows).most_common())
    tr_tasks = {c["meta"]["task"] for c in train}
    st = {"expert": EXPERT, "variant_of": "tb",
          "sources": {TRAJ_REPO: TRAJ_REV, ENV_REPO: ENV_REV}, "license": "Apache-2.0 (both datasets)",
          "teachers": {"deepseek": "deepseek-ai/DeepSeek-V4-Pro (MIT)", "glm": "zai-org/GLM-5.2 (MIT)",
                       "qwen": "Qwen/Qwen3.6-27B (Apache-2.0)", "gemma_think": "google/gemma-4-31B-it, thinking (Apache-2.0)"},
          "filters": {"reward": "== 1 (pytest verifier), counts_toward_k, status scored, not capped",
                      "difficulty": f"0 < pooled pass rate (6 configs) <= {HARD_MAX} (tier 1); <= {TIER2_MAX} tier 2 only if needed",
                      "max_per_task": MAX_PER_TASK, "min_assistant_turns": MIN_TURNS, "max_tokens": MAX_TOKENS,
                      "decontam": "TB1-unsafe/TB2 names, TB2 13-gram (instruction+solution vs TB2 instruction/solution/tests, k>=3), "
                                  "13-gram vs TBLite dev + E-TB val instructions (k>=3)",
                      "val": f"{N_VAL_TASKS} held-out tier-1 tasks (stable hash), 1 trajectory each"},
          "n_train": len(train), "n_val": len(val), "n_train_tasks": len(tr_tasks),
          "train_tokens": sum(c["n_tokens"] for c in train), "val_tokens": sum(c["n_tokens"] for c in val),
          "token_budget": TOKEN_BUDGET,
          "train_by_teacher": dist(train, lambda c: c["meta"]["teacher"]),
          "train_tokens_by_teacher": {m: sum(c["n_tokens"] for c in train if c["meta"]["teacher"] == m) for m in MODELS},
          "train_by_tier": dist(train, lambda c: c["meta"]["tier"]),
          "train_by_category": dist(train, lambda c: c["meta"]["category"]),
          "train_by_termgrade_split": dist(train, lambda c: c["meta"]["termgrade_split"]),
          "pooled_pass_of_train_tasks": {"median": statistics.median(tasks[t]["pooled"] for t in tr_tasks) if tr_tasks else None,
                                         "max": max((tasks[t]["pooled"] for t in tr_tasks), default=None)},
          "turns": {"median": statistics.median(c["meta"]["turns"] for c in train) if train else None,
                    "p90": sorted(c["meta"]["turns"] for c in train)[int(0.9 * len(train))] if train else None},
          "mean_tokens": round(sum(c["n_tokens"] for c in train) / max(1, len(train))),
          "n_candidates": len(cands), "candidates_by_teacher": dist(cands, lambda c: c["meta"]["teacher"]),
          "tasks_kept": len(tasks), "tasks_by_tier": dist(tasks.values(), lambda t: t["tier"]),
          "drops": dict(drops), "built_at": time.strftime("%Y-%m-%d %H:%M:%S")}
    (mani / f"{EXPERT}_stats.json").write_text(json.dumps(st, indent=1, default=str))
    log(f"[{EXPERT}] train={len(train)} ({st['train_tokens'] / 1e6:.2f}M tok, {len(tr_tasks)} tasks) "
        f"val={len(val)} by_teacher={st['train_by_teacher']} tiers={st['train_by_tier']}")
    return st


# ============================================================================= per-turn variant
# At eval Terminus-2 never sends earlier reasoning back and the server renders with
# {"enable_thinking": true, "preserve_thinking": false}: when generating turn k the model sees the task,
# earlier turns' visible JSON and the observations, but no earlier thinking. `build --per-turn` turns each
# trajectory into samples k = messages up to assistant turn k, earlier assistant turns WITHOUT reasoning,
# only turn k keeps it; records carry {"render": {"preserve_thinking": false}, "loss": "last_assistant"}
# (honoured by src/train/data.py), so the training context is byte-identical to the eval prompt.
EXPERT_TURNS = "tb_v2_turns"
VAL_TURNS_PER_TRAJ = 3
VAL_TOKEN_CAP = 650_000


def turn_records(s: dict) -> list[dict]:
    msgs = s["messages"]
    a_idx = [i for i, m in enumerate(msgs) if m["role"] == "assistant"]
    out = []
    for k, ai in enumerate(a_idx, start=1):
        ms = []
        for i, m in enumerate(msgs[: ai + 1]):
            m = dict(m)
            if m["role"] == "assistant" and i != ai:
                m.pop("reasoning_content", None)
            ms.append(m)
        out.append({"id": f"{s['id']}/t{k:02d}", "source": s["source"], "instance_id": s["instance_id"],
                    "messages": ms, "tools": None, "render": {"preserve_thinking": False},
                    "loss": "last_assistant",
                    "meta": {**s["meta"], "variant": EXPERT_TURNS, "turn": k, "n_turns_traj": len(a_idx)}})
    return out


def _train_len(rec: dict) -> int:
    tok = get_tokenizer()
    from .common import get_template
    text = tok.apply_chat_template(rec["messages"], tools=None, chat_template=get_template(), tokenize=False,
                                   add_generation_prompt=False)       # preserve_thinking not set (= eval)
    return len(tok(text, add_special_tokens=False)["input_ids"])


def _turn_worker(s: dict) -> list[dict]:
    recs = turn_records(s)
    for r in recs:
        r["meta"]["n_tokens_train"] = _train_len(r)
    return recs


def _verify_count_worker(r: dict) -> dict:
    from .common import count_tokens
    r["n_tokens"] = count_tokens(r["messages"], None)    # what `src.data.verify` recounts (preserve_thinking=True)
    return r


def build_turns(a):
    from .build import run_pool
    drops = DropCounter()
    get_tokenizer()
    tasks = task_table(drops)
    cands = candidates(tasks, drops, a.workers)
    by_task = defaultdict(list)
    for c in cands:
        by_task[c["meta"]["task"]].append(c)
    usable = [t for t in tasks if by_task.get(t)]
    val_tasks = sorted((t for t in usable if tasks[t]["tier"] == 1),
                       key=lambda t: stable_hash01(t, EXPERT + "|val"))[:N_VAL_TASKS]     # same as `build`
    vset = set(val_tasks)
    trajs = [s for t in usable if t not in vset for s in pick_per_task(by_task[t], MAX_PER_TASK)]
    trajs.sort(key=lambda s: (s["meta"]["tier"], stable_hash01(s["id"], EXPERT_TURNS)))
    val_trajs = [pick_per_task(by_task[t], 1)[0] for t in val_tasks]
    per_traj = {}
    for recs in run_pool(_turn_worker, trajs + val_trajs, a.workers):
        per_traj[recs[0]["id"].rsplit("/t", 1)[0]] = recs
    # train: round-robin over trajectories (tier 1 first), each round adds one more (stably shuffled) turn
    order = {sid: sorted(rs, key=lambda r: stable_hash01(r["id"], "turn")) for sid, rs in per_traj.items()}
    train, tok, rnd = [], 0, 0
    max_rounds = max((len(v) for v in order.values()), default=0)
    while tok < TOKEN_BUDGET and rnd < max_rounds:
        for s in trajs:
            rs = order[s["id"]]
            if rnd < len(rs) and tok < TOKEN_BUDGET:
                r = rs[rnd]
                train.append(r); tok += r["meta"]["n_tokens_train"]
        rnd += 1
    val, vtok = [], 0
    for s in val_trajs:
        for r in order[s["id"]][:VAL_TURNS_PER_TRAJ]:
            if vtok + r["meta"]["n_tokens_train"] <= VAL_TOKEN_CAP:
                val.append(r); vtok += r["meta"]["n_tokens_train"]
    train = list(run_pool(_verify_count_worker, train, a.workers))
    val = list(run_pool(_verify_count_worker, val, a.workers))
    out = processed_dir(EXPERT_TURNS)
    keep = ("id", "source", "instance_id", "messages", "tools", "render", "loss", "n_tokens", "meta")
    write_jsonl(out / "train.jsonl", ({k: c.get(k) for k in keep} for c in train))
    write_jsonl(out / "val.jsonl", ({k: c.get(k) for k in keep} for c in val))
    mani = APEX / "data" / "manifests"
