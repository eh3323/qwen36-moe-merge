"""E-TB-v2 side experiment data: TermGrade (test-verified Terminus-2 trajectories) -> E-TB training format.

Why: E-TB (Nemotron-Terminal-Corpus + OpenThoughts-Agent-SFT-100K) is not success-filtered ("complete" =
the teacher declared task_complete; 112 trajectories never even did) and the expert scored below Base on
TB2, with failures that claim verifications which never happened. This set keeps the E-TB recipe (same
schema, Terminus-2 text protocol re-rendered with the locked Harbor template, ~15.02M train tokens) but uses
  * ai-and/termgrade-trajectories @ TRAJ_REV (Apache-2.0): Terminus-2 (Harbor) episodes graded by each task's
    pytest verifier offline in a fresh container; ONLY reward == 1 trials that count toward the reported k;
  * ai-and/termgrade-environments @ ENV_REV: 1,004 executable tasks (generated by DeepSeek-V4-Pro, kept only
    if the reference solution passes its own verifier), checked by the authors against TB2.1;
  * hard tasks: some model solves them, pooled pass rate over the 6 graded configs <= HARD_MAX (a looser tier
    is used only if the token budget is not met), at most MAX_PER_TASK trajectories per task, longer
    multi-step trajectories from the strongest teachers preferred;
  * teachers: DeepSeek-V4-Pro (MIT), GLM-5.2 (MIT), Qwen3.6-27B (Apache-2.0), Gemma-4-31B-it thinking
    (Apache-2.0). Kimi-K3 is excluded (license "other").

Conversion (what Terminus-2 @ harbor 4778ceba sends at eval):
  first user   TermGrade splits the Terminus-2 prompt into system (template prefix, an older revision) and
               user ("Task Description: ... Current terminal state: ..."); instruction and initial screen are
               parsed back and re-rendered with the locked template (convert_terminus.render_first_user).
  assistant    bare Terminus-2 JSON (```json fences stripped), validated with parse_t2_json;
               reasoning kept in `reasoning_content` (same field as the existing E-TB data).
  observations Harbor's own strings ("New Terminal Output:", completion confirmation, warnings) are kept;
               the "Extra text before/after JSON" warning items are removed (convert_terminus.clean_observation);
               trajectories with any parsing-error feedback or context summarisation are dropped.
  the trailing observation after the final confirmed `task_complete: true` is removed.

usage (cluster, CPU job: slurm/data_build_tb_v2.sbatch):
  python -m src.data.build_tb_v2 download
  python -m src.data.build_tb_v2 build --workers 15
  python -m src.data.verify --experts tb_v2 --recount 50
Outputs: $APEX/data/processed/tb_v2/{train,val}.jsonl, $APEX/data/manifests/tb_v2_{train,val}.csv,
         $APEX/data/manifests/tb_v2_stats.json, $APEX/data/interim/tb_v2/{candidates,tasks}.jsonl
"""
from __future__ import annotations

