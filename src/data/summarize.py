"""Render $APEX/data/manifests/SUMMARY.md (final counts, tokens, drop counts) from the *_stats.json files.

usage: python -m src.data.summarize      (run after finalize; then scripts/fetch_data_manifests.sh)
"""
from __future__ import annotations

import json
from collections import defaultdict

from .common import APEX

MANI = APEX / "data" / "manifests"


def main():
    out = ["# Data build summary (auto-generated by `python -m src.data.summarize`)\n",
           "| expert | train n | train tokens | mean tok/sample | val n | val tokens | candidates |",
           "|---|---|---|---|---|---|---|"]
    stats = {}
    for e in ("swe", "tb", "asi", "hle"):
        p = MANI / f"{e}_stats.json"
        if not p.exists():
            continue
        s = stats[e] = json.loads(p.read_text())
        out.append(f"| {e} | {s['n_train']} | {s['train_tokens']:,} | {s['mean_tokens']:,} | {s['n_val']} | "
                   f"{s['val_tokens']:,} | {s.get('n_candidates', '')} |")
    mp = MANI / "mixed_stats.json"
    if mp.exists():
        m = json.loads(mp.read_text())
        out.append(f"| mixed | {m['train']['n']} | {m['train']['tokens']:,} | | {m['val']['n']} | {m['val']['tokens']:,} | |")
    for e, s in stats.items():
        out.append(f"\n## {e}\n")
        out.append("train by source: " + ", ".join(f"{k}={v}" for k, v in s["train_by_source"].items()))
        out.append("\ntrain tokens by source: " + ", ".join(f"{k}={v:,}" for k, v in s["train_tokens_by_source"].items()))
        out.append("\ntrain by stratum: " + ", ".join(f"{k}={v}" for k, v in s["train_by_stratum"].items()))
        for k in ("candidates_by_stratum", "candidates_by_source", "confidence_hist", "n_heldout_dev"):
            if k in s:
                out.append(f"\n{k}: {json.dumps(s[k])}")
        by_src = defaultdict(list)
        for k, v in sorted(s["drops"].items(), key=lambda x: -x[1]):
            src, _, why = k.partition(":")
            by_src[src].append((why, v))
        out.append("\n| source | drop reason | count |\n|---|---|---|")
        for src, lst in by_src.items():
            for why, v in lst:
                out.append(f"| {src} | {why} | {v} |")
    (MANI / "SUMMARY.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
