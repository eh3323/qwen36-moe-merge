#!/usr/bin/env python3
"""Copy the generated result tables into README §8 (between <!-- results:begin --> and <!-- results:end -->).

    python3 analysis/make_tables.py && python3 analysis/readme_results.py

Source: analysis/results_tables.md (written by make_tables.py from results/*.jsonl via summarize.py). Only the
sections are re-arranged and the table headers translated; no number is computed here.
"""
from __future__ import annotations

import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "analysis", "results_tables.md")
README = os.path.join(REPO, "README.md")
BEGIN, END = "<!-- results:begin -->", "<!-- results:end -->"

HEADERS = [
    ("| Benchmark | Base |", "| Benchmark | Base |"),
    ("**Macro average (4 benchmarks)**", "**宏平均（4 项）**"),
    ("| Benchmark | v4 − Base | Mixed − Base | v4 − Mixed |", "| Benchmark | v4 − Base | Mixed − Base | v4 − Mixed |"),
    ("**Macro**", "**宏平均**"),
    ("— partial: over", "（仅含"),
    ("Comparison (B vs A)", "比较（B vs A）"), ("n tasks", "任务数"),
    ("Δ = B − A [95% CI], p", "Δ = B − A [95% CI], p"), ("McNemar (A-only:B-only)", "McNemar（A 独赢 : B 独赢）"),
    ("env_err A / B", "env_error A / B"), ("Δ, env_error dropped", "Δ（剔除 env_error）"),
    ("| Model |", "| 模型 |"), ("mean ± std (n)", "均值 ± std（次数）"),
    ("env_error per run", "每次 env_error"), ("timeout per run", "每次 timeout"),
    ("Terminal-Bench 2.0", "Terminal-Bench 2.0"), ("pending (partial run)", "未完成"), ("pending", "未完成"),
    ("(hist.)", "（历史）"), ("Base (cluster TB2)", "Base（集群 TB2）"), ("v4 (cluster TB2)", "v4（集群 TB2）"),
    ("Base (all TB2 runs)", "Base（全部 TB2 运行）"), ("v4 (all TB2 runs)", "v4（全部 TB2 运行）"),
    (" (missing ", "（缺 "),
]


def section(text: str, title_re: str) -> str:
    """Body of the section whose heading matches title_re, up to the next heading of the same or higher level."""
    m = re.search(rf"^(#+) {title_re}.*$", text, re.M)
    if not m:
        raise SystemExit(f"section not found: {title_re}")
    rest = text[m.end():]
    nxt = re.search(r"^#+ ", rest, re.M)
    return rest[: nxt.start()] if nxt else rest


def table(body: str) -> str:
    lines = [l for l in body.splitlines() if l.startswith("|")]
    out = "\n".join(lines)
    for a, b in HEADERS:
        out = out.replace(a, b)
    return out.replace("only", "）") if "（仅含" in out else out


def plain(body: str) -> str:
    """Non-table text lines of a section (e.g. the historical / calibration notes)."""
    return [l for l in body.splitlines() if l.strip() and not l.startswith("|")]


def main() -> None:
    src = open(SRC).read()
    gen = re.search(r"generated by analysis/make_tables.py at (\S+);", src).group(1)
    a, b = section(src, r"\(a\) Score matrix"), section(src, r"\(b\) Δ vs Base")
    b1, b2 = section(src, r"\(b′\) Sensitivity"), section(src, r"\(b2\) All comparisons")
    d, d1 = section(src, r"\(d\) Per-run scores"), section(src, r"\(d′\) Per-run scores")
    notes = [table("|" + l)[1:] for l in plain(a) if l.startswith(("Historical", "HLE RMS"))]
    block = f"""{BEGIN}
<!-- 由 analysis/readme_results.py 从 analysis/results_tables.md（{gen}）复制，勿手改；完整版含失败率与 token 用量见该文件 -->

### 8.1 分数矩阵

主指标为百分制，env_error 按 0 分计入（§9）。多次运行时为均值 ± 标准差（ddof=1）及次数。TB2 只用 Nebius VM 上的运行（所有模型同一节点、同一设置，§11 第 21 条）；集群上的 TB2 运行见 8.3。“—”表示不在该模型的评测范围内。

{table(a)}

{chr(10).join("- " + n.replace("Historical runs (not in the matrix): ", "不在矩阵中的运行：").replace("HLE RMS calibration error (official hle_eval, β=100): ", "HLE 校准误差（官方 hle_eval，RMS，β=100）：") for n in notes)}

### 8.2 相对 Base 的差值（95% CI）

配对 bootstrap（按任务配对，每个任务取该模型所有运行的平均分，10,000 次重采样，seed 0），p 为双侧 bootstrap p。宏平均为四项等权，在每个 benchmark 内分别重采样（§9）。

{table(b)}

敏感性分析：剔除任一方出现 env_error 的任务。

{table(b1)}

### 8.3 全部配对比较

McNemar 精确检验只在两边每题都只有一个二元结果（单次运行）时给出。

{table(b2)}

### 8.4 每次运行的分数

TB2（89 题）。模型名行是 Nebius VM 上的运行（Docker、TP=2）；“集群 TB2”行是集群上的运行（apptainer、单卡）；“全部 TB2 运行”把两者合并，其中 `c` 前缀的列来自 Nebius。

{table(d)}

SWE-bench Pro HARD-51（51 题，全部重新判分后）。

{table(d1)}
{END}"""
    readme = open(README).read()
    if BEGIN in readme:
        readme = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, readme, flags=re.S)
    else:
        raise SystemExit(f"README has no {BEGIN} marker")
    open(README, "w").write(readme)
    print(f"README §8 updated from results_tables.md ({gen})")


if __name__ == "__main__":
    main()
